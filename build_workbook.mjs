import fs from 'node:fs/promises';
import path from 'node:path';
import {Workbook,SpreadsheetFile} from '@oai/artifact-tool';
const root=process.argv[2]||'.';
const d=JSON.parse(await fs.readFile(path.join(root,'qa/analysis.json'),'utf8'));
const wb=Workbook.create();
const names=['Итоги','Сводная','Вознаграждения','Пациент месяц','Услуги','Уникальные','Параметры'];
const sheets=Object.fromEntries(names.map(n=>[n,wb.worksheets.add(n)]));
function block(name,headers,rows,tableName,start=1){
 const s=sheets[name]; const matrix=[headers,...rows];
 s.getRangeByIndexes(start-1,0,matrix.length,headers.length).values=matrix;
 const range=s.getRangeByIndexes(start-1,0,matrix.length,headers.length);
 range.format.font={name:'Arial',size:10,color:'#24364B'};
 range.format.rowHeight=23; range.format.verticalAlignment='center';
 range.format.columnWidth=19;
 s.getRangeByIndexes(start-1,0,1,headers.length).format={fill:'#244763',font:{bold:true,color:'#FFFFFF'},rowHeight:32,wrapText:true};
 if(tableName) s.tables.add(`${'A'+start}:${String.fromCharCode(64+headers.length)}${start+rows.length}`,true,tableName);
 s.showGridLines=false;if(rows.length>15)s.freezePanes.freezeRows(start);
 return s;
}
