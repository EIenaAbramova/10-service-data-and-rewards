block('Услуги',['Файл','Строка','id пациента','возраст','дата услуги','Месяц','клиника услуги','компенсация, руб.','представитель','Возрастная категория','Канал привлечения'],d.rows,'ServicesData');
sheets['Услуги'].getRange(`D2:D${R}`).setNumberFormat('0.00');
sheets['Услуги'].getRange(`H2:H${R}`).setNumberFormat('#,##0.00');
sheets['Услуги'].getRange(`I1:I${R}`).format.columnWidth=42;
sheets['Услуги'].getRange(`J1:K${R}`).format.columnWidth=24;
block('Пациент месяц',['Месяц','id пациента','представитель','Возрастная категория','Оплата за месяц, руб.','Вознаграждение, руб.','Строк услуг'],d.ledger,'PatientMonths');
sheets['Пациент месяц'].getRange(`C1:C${L}`).format.columnWidth=42;
sheets['Пациент месяц'].getRange(`D1:G${L}`).format.columnWidth=25;
sheets['Пациент месяц'].getRange(`E2:F${L}`).setNumberFormat('#,##0.00');
sheets['Пациент месяц'].getRange('F2').formulas=[['=IF(C2="",0,IF(A2="2024-07",IF(AND(D2="дети",E2>100000),5000,0),IF(OR(A2="2024-08",A2="2024-09"),IF(E2>120000,8000,0),NA())))']];
sheets['Пациент месяц'].getRange(`F2:F${L}`).fillDown();
block('Уникальные',['Месяц','клиника услуги','Канал привлечения','id пациента','Единица'],d.unique,'UniquePatients');
sheets['Уникальные'].getRange(`B1:C${d.unique.length+1}`).format.columnWidth=36;
const payoutRows=d.payments.map(r=>[...r,r.slice(1).reduce((a,b)=>a+b,0)]);
block('Вознаграждения',['представитель',...d.months,'Всего, руб.'],payoutRows,'PartnerRewards',4);
sheets['Вознаграждения'].getRange('A2').values=[['Вознаграждения представителям']];
sheets['Вознаграждения'].getRange('A2').format.font={name:'Arial',size:15,bold:true};
sheets['Вознаграждения'].getRange(`A4:A${payoutRows.length+4}`).format.columnWidth=43;
for(let i=0;i<payoutRows.length;i++){
 const r=i+5;
 for(let j=0;j<d.months.length;j++)sheets['Вознаграждения'].getCell(r-1,j+1).formulas=[[`=SUMIFS('Пациент месяц'!$F$2:$F$${L},'Пациент месяц'!$C$2:$C$${L},$A${r},'Пациент месяц'!$A$2:$A$${L},${String.fromCharCode(66+j)}$4)`]];
 sheets['Вознаграждения'].getCell(r-1,4).formulas=[[`=SUM(B${r}:D${r})`]];
}
sheets['Вознаграждения'].getRange(`B5:E${payoutRows.length+4}`).setNumberFormat('#,##0');
block('Итоги',['Месяц','Строк услуг','Уникальных пациентов','Компенсация, руб.','Пациентов с выплатой','Вознаграждение, руб.'],d.summary,'MonthlySummary',5);
sheets['Итоги'].getRange('A2').values=[[process.argv.includes('--public')?'Клиника  Демонстрация':'Клиника']];
sheets['Итоги'].getRange('B2').values=[['Июль — сентябрь 2024']];
sheets['Итоги'].getRange('A2').format.font={name:'Arial',size:15,bold:true};
sheets['Итоги'].getRange('A10:B14').values=[['Показатель за период','Значение'],['Строк услуг',d.controls.rows],['Уникальных пациентов',d.controls.patients_period],['Компенсация, руб.',d.controls.compensation],['Вознаграждение, руб.',d.controls.reward]];
sheets['Итоги'].tables.add('A10:B14',true,'PeriodSummary');
sheets['Итоги'].getRange('A16').values=[['Месяц — дата услуги']];
sheets['Итоги'].getRange('A17').values=[['Выплата за пациента в месяц']];
sheets['Итоги'].getRange('A18').values=[['Сумма групп ≠ число людей']];
sheets['Итоги'].getRange('A19').values=[['Обновление — см. конспект']];
sheets['Итоги'].getRange('A20').values=[['Обновление в Excel не проверено']];
sheets['Итоги'].getRange('A10:A14').format.columnWidth=31;
sheets['Итоги'].getRange('B5:F8').format.columnWidth=25;
sheets['Итоги'].getRange('D6:D8').setNumberFormat('#,##0.00');
sheets['Итоги'].getRange('F6:F8').setNumberFormat('#,##0');
for(let i=0;i<d.summary.length;i++){
 const r=i+6;
 sheets['Итоги'].getRange(`D${r}`).formulas=[[`=SUMIFS('Услуги'!$H$2:$H$${R},'Услуги'!$F$2:$F$${R},A${r})`]];
 sheets['Итоги'].getRange(`F${r}`).formulas=[[`=SUMIFS('Пациент месяц'!$F$2:$F$${L},'Пациент месяц'!$A$2:$A$${L},A${r})`]];
}
sheets['Итоги'].getRange('B13').formulas=[['=SUM(D6:D8)']];
sheets['Итоги'].getRange('B14').formulas=[['=SUM(F6:F8)']];
sheets['Итоги'].getRange('B13:B14').setNumberFormat('#,##0.00');
const pairs=[...new Set(d.unique.map(r=>JSON.stringify([r[1],r[2]])))].sort().map(JSON.parse);
const pivotRows=pairs.map(([clinic,ch])=>[clinic,ch,...d.months.map(m=>d.counts.find(r=>r[0]===m&&r[1]===clinic&&r[2]===ch)?.[3]||0)]);
block('Сводная',['клиника услуги','Канал привлечения',...d.months],pivotRows,null,4);
sheets['Сводная'].getRange('A2').values=[['Уникальные пациенты']];
sheets['Сводная'].getRange('B2').values=[['Клиники и каналы']];
sheets['Сводная'].getRange('A2').format.font={name:'Arial',size:15,bold:true};
sheets['Сводная'].getRange(`A4:A${pivotRows.length+4}`).format.columnWidth=43;
sheets['Сводная'].getRange(`B4:B${pivotRows.length+4}`).format.columnWidth=23;
block('Параметры',['Параметр','Значение'],[['Папка выгрузок',process.argv.includes('--public')?'C:\\Services_DEMO':path.resolve(root,'Выгрузки')],['Период','2024-07 — 2024-09'],['Июль: порог, руб.',100000],['Июль: выплата, руб.',5000],['Август и сентябрь: порог, руб.',120000],['Август и сентябрь: выплата, руб.',8000]],null);
sheets['Параметры'].getRange('A1:A7').format.columnWidth=43;
sheets['Параметры'].getRange('B1:B7').format.columnWidth=80;
sheets['Параметры'].getRange('B2').format.fill='#FFF2CC';
sheets['Параметры'].getRange('B2').format.wrapText=true;
sheets['Параметры'].getRange('A2:B2').format.rowHeight=42;
wb.recalculate();
await fs.writeFile(path.join(root,'qa/inspection.txt'),(await wb.inspect({kind:'region',sheetId:'Итоги',range:'A5:F14',maxChars:4500,tableMaxRows:12,tableMaxCols:6})).ndjson);
await fs.writeFile(path.join(root,'qa/summary.png'),new Uint8Array(await (await wb.render({sheetName:'Итоги',autoCrop:'all',scale:1.3,format:'png'})).arrayBuffer()));
await (await SpreadsheetFile.exportXlsx(wb)).save(path.join(root,'10_Расчёт_вознаграждений.xlsx'));
